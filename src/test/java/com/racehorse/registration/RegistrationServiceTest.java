/** Isolated H2 contract proof only; never connects to or mutates a SQL Server database. */
class RegistrationServiceTest {
    JdbcTemplate jdbc;
    RegistrationService service;
    BCryptPasswordEncoder encoder=new BCryptPasswordEncoder(10);
    Instant now=Instant.parse("2026-10-21T08:00:00Z");
    @BeforeEach void setup(){
        JdbcDataSource ds=new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:registration_"+UUID.randomUUID()+";MODE=MSSQLServer;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000");
        jdbc=new JdbcTemplate(ds);jdbc.execute("CREATE SCHEMA dbo");
        jdbc.execute("CREATE TABLE dbo.role(id BIGINT PRIMARY KEY,role_code VARCHAR(30) NOT NULL UNIQUE)");
        jdbc.execute("""
            CREATE TABLE dbo.app_user(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_code VARCHAR(20) UNIQUE NOT NULL,
                full_name NVARCHAR(150) NOT NULL,email NVARCHAR(254) UNIQUE NOT NULL,password_hash VARCHAR(255),
                account_status VARCHAR(20) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,last_login_at TIMESTAMP)
            """);
        jdbc.execute("""
            CREATE TABLE dbo.user_role(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT REFERENCES dbo.app_user,
                role_id BIGINT REFERENCES dbo.role,assigned_by_user_id BIGINT REFERENCES dbo.app_user,assigned_at TIMESTAMP,created_at TIMESTAMP)
            """);
        // H2 MSSQL mode permits only one NULL in a unique index. Distinct decided-row keys emulate
        // the canonical filtered pending-email index without weakening pending-email uniqueness.
        jdbc.execute("""
            CREATE TABLE dbo.registration_request(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name NVARCHAR(150) NOT NULL,
                email NVARCHAR(254) NOT NULL,email_normalized NVARCHAR(254) NOT NULL,password_hash VARCHAR(255),status VARCHAR(20) NOT NULL,
                requested_at TIMESTAMP NOT NULL,reviewed_by_user_id BIGINT REFERENCES dbo.app_user,reviewed_at TIMESTAMP,
                decision_reason NVARCHAR(500),approved_role_id BIGINT REFERENCES dbo.role,created_user_id BIGINT REFERENCES dbo.app_user,
                created_at TIMESTAMP,updated_at TIMESTAMP,
                pending_email NVARCHAR(300) GENERATED ALWAYS AS (CASE WHEN status='PENDING_APPROVAL' THEN CONCAT('P:',email_normalized) ELSE CONCAT('D:',CAST(id AS VARCHAR)) END),
                UNIQUE(pending_email),CHECK((status='PENDING_APPROVAL' AND password_hash IS NOT NULL) OR (status<>'PENDING_APPROVAL' AND password_hash IS NULL)))
            """);
        jdbc.execute("""
            CREATE TABLE dbo.audit_log(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_user_id BIGINT,actor_role VARCHAR(30),
                action VARCHAR(100),target_type VARCHAR(50),target_id BIGINT,safe_summary NVARCHAR(1000),source VARCHAR(30),occurred_at TIMESTAMP)
            """);
        for(var role:RoleCode.values())jdbc.update("INSERT INTO dbo.role(id,role_code) VALUES(?,?)",role.ordinal()+1,role.name());
        jdbc.update("INSERT INTO dbo.app_user(user_code,full_name,email,account_status) VALUES('U-001','Manager','manager@example.test','ACTIVE')");
        jdbc.update("INSERT INTO dbo.user_role(user_id,role_id) VALUES(1,?)",RoleCode.CLUB_MANAGER.ordinal()+1);
        service=new RegistrationService(new RegistrationRepository(jdbc),new AuthRepository(jdbc),encoder,
                new RegistrationRateLimiter(),new DataSourceTransactionManager(ds),Clock.fixed(now,ZoneOffset.UTC));
    }
    Register input(String email){var r=new Register();r.fullName="Applicant";r.email=email;r.password="Password123";r.confirmPassword=r.password;return r;}
    long pending(String email){service.register(input(email),"127.0.0.1");return jdbc.queryForObject("SELECT id FROM dbo.registration_request WHERE email_normalized=?",Long.class,email);}
    @Test void createsOnlyPendingAndHashesImmediately(){
        var first=service.register(input(" Test@Example.test "),"127.0.0.1");
        var duplicate=service.register(input("test@example.test"),"127.0.0.1");
        var existing=service.register(input("manager@example.test"),"127.0.0.1");
        assertEquals(first,duplicate);assertEquals(first,existing);
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request",Integer.class));
        String hash=jdbc.queryForObject("SELECT password_hash FROM dbo.registration_request",String.class);
        assertTrue(hash.startsWith("$2"));assertTrue(encoder.matches("Password123",hash));
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.app_user",Integer.class));
        assertFalse(new Register().toString().contains("Password123"));
    }
    @Test void approvalCopiesHashCreatesOneRoleClearsRequestAndAudits(){
        long id=pending("approve@example.test");
        String hash=jdbc.queryForObject("SELECT password_hash FROM dbo.registration_request WHERE id=?",String.class,id);
        var result=service.approve(1,id,RoleCode.TRAINER);
        assertEquals(Status.APPROVED,result.status());assertEquals(RoleCode.TRAINER,result.approvedRoleCode());
        assertEquals(hash,jdbc.queryForObject("SELECT password_hash FROM dbo.app_user WHERE id=?",String.class,result.createdUserId()));
        assertNull(jdbc.queryForObject("SELECT password_hash FROM dbo.registration_request WHERE id=?",String.class,id));
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.user_role WHERE user_id=?",Integer.class,result.createdUserId()));
        assertEquals(2,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.audit_log",Integer.class));
        assertTrue(jdbc.queryForList("SELECT safe_summary FROM dbo.audit_log",String.class).stream().noneMatch(s->s.contains(hash)||s.contains("Password123")));
        assertEquals(ErrorCode.CONFLICT,assertThrows(BusinessException.class,()->service.approve(1,id,RoleCode.GROOM)).code());
    }
    @Test void rejectClearsHashAndRetainsReasonOnlyOnManagerProjection(){
        long id=pending("reject@example.test");var result=service.reject(1,id,"Please confirm membership.");
        assertEquals(Status.REJECTED,result.status());assertEquals("Please confirm membership.",result.decisionReason());
        assertNull(jdbc.queryForObject("SELECT password_hash FROM dbo.registration_request WHERE id=?",String.class,id));
        assertEquals(ErrorCode.CONFLICT,assertThrows(BusinessException.class,()->service.reject(1,id,null)).code());
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.audit_log WHERE action='REGISTRATION_REJECTED'",Integer.class));
    }
    @Test void cooldownAndThreeRejectionsAreNeutral(){
        long id=pending("cooldown@example.test");service.reject(1,id,null);
        var neutral=service.register(input("cooldown@example.test"),"127.0.0.2");
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request",Integer.class));
        jdbc.update("UPDATE dbo.registration_request SET reviewed_at=? WHERE id=?",LocalDateTime.ofInstant(now.minus(Duration.ofDays(7)),ZoneOffset.UTC),id);
        assertEquals(neutral,service.register(input("cooldown@example.test"),"127.0.0.2"));
        assertEquals(2,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request",Integer.class));
        for(int i=0;i<3;i++)jdbc.update("INSERT INTO dbo.registration_request(full_name,email,email_normalized,status,requested_at,reviewed_at) VALUES('Blocked','blocked@example.test','blocked@example.test','REJECTED',?,?)",LocalDateTime.ofInstant(now.minus(Duration.ofDays(10)),ZoneOffset.UTC),LocalDateTime.ofInstant(now.minus(Duration.ofDays(8)),ZoneOffset.UTC));
        assertEquals(neutral,service.register(input("blocked@example.test"),"127.0.0.3"));
        assertEquals(3,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request WHERE email_normalized='blocked@example.test'",Integer.class));
    }
    @Test void filteredPendingUniquenessAllowsHistoryButRejectsDuplicatePending(){
        long id=pending("unique@example.test");
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class,()->jdbc.update(
                "INSERT INTO dbo.registration_request(full_name,email,email_normalized,password_hash,status,requested_at) VALUES('Duplicate','unique@example.test','unique@example.test','HASH','PENDING_APPROVAL',?)",
                LocalDateTime.ofInstant(now,ZoneOffset.UTC)));
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request WHERE status='PENDING_APPROVAL'",Integer.class));
        service.reject(1,id,null);
        for(int i=0;i<2;i++)jdbc.update(
                "INSERT INTO dbo.registration_request(full_name,email,email_normalized,status,requested_at,reviewed_at) VALUES('History','unique@example.test','unique@example.test','REJECTED',?,?)",
                LocalDateTime.ofInstant(now,ZoneOffset.UTC),LocalDateTime.ofInstant(now,ZoneOffset.UTC));
        assertEquals(3,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request WHERE email_normalized='unique@example.test' AND status='REJECTED'",Integer.class));
    }
    @Test void emailCollisionRollsBackAndLeavesPending(){
        long id=pending("collision@example.test");
        jdbc.update("INSERT INTO dbo.app_user(user_code,full_name,email,account_status) VALUES('U-OTHER','Other','collision@example.test','ACTIVE')");
        assertEquals(ErrorCode.CONFLICT,assertThrows(BusinessException.class,()->service.approve(1,id,RoleCode.GROOM)).code());
        assertEquals("PENDING_APPROVAL",jdbc.queryForObject("SELECT status FROM dbo.registration_request WHERE id=?",String.class,id));
        assertNotNull(jdbc.queryForObject("SELECT password_hash FROM dbo.registration_request WHERE id=?",String.class,id));
        assertEquals(0,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.audit_log",Integer.class));
    }
    @Test void deniedRolesInactiveAndInvalidPagination(){
        // Replace with an approved but unauthorized role, never an invented authority.
        jdbc.update("UPDATE dbo.user_role SET role_id=? WHERE user_id=1",RoleCode.GROOM.ordinal()+1);
        assertEquals(ErrorCode.FORBIDDEN,assertThrows(BusinessException.class,()->service.list(1,null,0,20)).code());
        jdbc.update("UPDATE dbo.user_role SET role_id=? WHERE user_id=1",RoleCode.CLUB_MANAGER.ordinal()+1);
        jdbc.update("UPDATE dbo.app_user SET account_status='INACTIVE' WHERE id=1");
        assertEquals(ErrorCode.FORBIDDEN,assertThrows(BusinessException.class,()->service.list(1,null,0,20)).code());
        jdbc.update("UPDATE dbo.app_user SET account_status='ACTIVE' WHERE id=1");
        assertEquals(ErrorCode.VALIDATION_ERROR,assertThrows(BusinessException.class,()->service.list(1,null,0,101)).code());
    }
    @Test void passwordValidationAndRateLimitsDoNotLeakExistence(){
        var invalid=input("bad@example.test");invalid.password="A".repeat(8);invalid.confirmPassword=invalid.password;
        assertEquals(ErrorCode.VALIDATION_ERROR,assertThrows(BusinessException.class,()->service.register(invalid,"ip")).code());
        invalid.password="é".repeat(36)+"1";invalid.confirmPassword=invalid.password;
        assertEquals(ErrorCode.VALIDATION_ERROR,assertThrows(BusinessException.class,()->service.register(invalid,"ip")).code());
        for(int i=0;i<3;i++)service.register(input("manager@example.test"),"different-ip-"+i);
        assertEquals(ErrorCode.TOO_MANY_REQUESTS,assertThrows(BusinessException.class,()->service.register(input("manager@example.test"),"another-ip")).code());
        var limiter=new RegistrationRateLimiter();for(int i=0;i<5;i++)limiter.consume("one-ip","email"+i,now);
        assertEquals(ErrorCode.TOO_MANY_REQUESTS,assertThrows(BusinessException.class,()->limiter.consume("one-ip","another-email",now)).code());
        assertDoesNotThrow(()->limiter.consume("one-ip","another-email",now.plus(Duration.ofMinutes(15))));
    }
    @Test void unrelatedPersistenceFailureIsNeverNeutralSuccess(){
        var repository=mock(RegistrationRepository.class);
        when(repository.canRegister("store-error@example.test",now)).thenReturn(true);
        doThrow(new org.springframework.dao.DataIntegrityViolationException("fixture storage failure"))
                .when(repository).create(org.mockito.ArgumentMatchers.anyString(),org.mockito.ArgumentMatchers.anyString(),
                        org.mockito.ArgumentMatchers.anyString(),org.mockito.ArgumentMatchers.eq(now));
        var failing=new RegistrationService(repository,new AuthRepository(jdbc),encoder,new RegistrationRateLimiter(),
                new DataSourceTransactionManager(jdbc.getDataSource()),Clock.fixed(now,ZoneOffset.UTC));
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class,
                ()->failing.register(input("store-error@example.test"),"ip"));
        assertEquals(0,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.registration_request",Integer.class));
    }
    @Test void concurrentDoubleApproveHasExactlyOneDecision()throws Exception{
        long id=pending("double@example.test");var start=new CountDownLatch(1);
        try(var pool=Executors.newFixedThreadPool(2)){
            Callable<String> action=()->{start.await();try{service.approve(1,id,RoleCode.TRAINER);return "OK";}catch(BusinessException ex){return ex.code().name();}};
            var a=pool.submit(action);var b=pool.submit(action);start.countDown();
            var outcomes=List.of(a.get(10,TimeUnit.SECONDS),b.get(10,TimeUnit.SECONDS));
            assertEquals(1,Collections.frequency(outcomes,"OK"));assertEquals(1,Collections.frequency(outcomes,"CONFLICT"));
        }
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.app_user WHERE email='double@example.test'",Integer.class));
    }
}
