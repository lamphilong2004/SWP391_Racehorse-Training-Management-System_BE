package com.racehorse.horse.owner;

import com.racehorse.TestJwtProperties;
import com.racehorse.auth.AccountStatus;
import com.racehorse.auth.JwtTokenService;
import com.racehorse.auth.RoleCode;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.security.test.web.servlet.setup.SecurityMockMvcConfigurers;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.web.context.WebApplicationContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;

import java.sql.PreparedStatement;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicLong;

abstract class OwnerApiIntegrationTestSupport {

    private static final AtomicLong NEXT_USER_ID = new AtomicLong(9_000_000_000L);

    @Autowired
    protected JdbcTemplate jdbcTemplate;

    @Autowired
    protected WebApplicationContext webApplicationContext;

    @Autowired
    private JwtTokenService jwtTokenService;

    protected MockMvc mockMvc;

    private final List<Long> createdUserIds = new ArrayList<>();
    private final List<Long> createdHorseIds = new ArrayList<>();

    @DynamicPropertySource
    static void jwtProperties(DynamicPropertyRegistry registry) {
        TestJwtProperties.register(registry);
        registry.add("springdoc.api-docs.enabled", () -> true);
    }

    @BeforeEach
    void prepareOwnerApiSchema() {
        createdUserIds.clear();
        createdHorseIds.clear();
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS dbo.horse (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_code VARCHAR(20) NOT NULL UNIQUE,
                    name NVARCHAR(150) NOT NULL,
                    breed NVARCHAR(100),
                    sex NVARCHAR(20),
                    foaled_date DATE,
                    country_of_origin NVARCHAR(100),
                    registration_no VARCHAR(50),
                    lifecycle VARCHAR(20) NOT NULL,
                    health_status VARCHAR(20),
                    sire_horse_id BIGINT,
                    sire_name NVARCHAR(150),
                    dam_horse_id BIGINT,
                    dam_name NVARCHAR(150),
                    activated_at TIMESTAMP(3),
                    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (sire_horse_id) REFERENCES dbo.horse (id),
                    FOREIGN KEY (dam_horse_id) REFERENCES dbo.horse (id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS dbo.horse_ownership (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_id BIGINT NOT NULL,
                    owner_user_id BIGINT NOT NULL,
                    share_percentage DECIMAL(5,2) NOT NULL,
                    effective_from DATE NOT NULL,
                    effective_to DATE,
                    is_managing_owner BOOLEAN NOT NULL,
                    FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
                    FOREIGN KEY (owner_user_id) REFERENCES dbo.app_user (id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS dbo.medical_restriction (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_id BIGINT NOT NULL,
                    set_by_user_id BIGINT NOT NULL,
                    restriction_level VARCHAR(20) NOT NULL,
                    reason NVARCHAR(1000) NOT NULL,
                    effective_from TIMESTAMP(3) NOT NULL,
                    lifted_at TIMESTAMP(3),
                    review_date DATE,
                    FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
                    FOREIGN KEY (set_by_user_id) REFERENCES dbo.app_user (id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS dbo.medical_case (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_id BIGINT NOT NULL,
                    opened_by_user_id BIGINT NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    opened_at TIMESTAMP(3) NOT NULL,
                    closed_at TIMESTAMP(3),
                    condition_summary NVARCHAR(2000),
                    FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
                    FOREIGN KEY (opened_by_user_id) REFERENCES dbo.app_user (id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS dbo.veterinary_examination (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_id BIGINT NOT NULL,
                    medical_case_id BIGINT,
                    performed_by_user_id BIGINT NOT NULL,
                    exam_type VARCHAR(20) NOT NULL,
                    examined_at TIMESTAMP(3) NOT NULL,
                    findings NVARCHAR(1000),
                    diagnosis NVARCHAR(1000),
                    recovery_outcome VARCHAR(20),
                    FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
                    FOREIGN KEY (medical_case_id) REFERENCES dbo.medical_case (id),
                    FOREIGN KEY (performed_by_user_id) REFERENCES dbo.app_user (id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS dbo.weight_record (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_id BIGINT NOT NULL,
                    recorded_by_user_id BIGINT NOT NULL,
                    weight DECIMAL(6,2) NOT NULL,
                    measured_at TIMESTAMP(3) NOT NULL,
                    context NVARCHAR(50),
                    FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
                    FOREIGN KEY (recorded_by_user_id) REFERENCES dbo.app_user (id)
                )
                """);
        mockMvc = MockMvcBuilders.webAppContextSetup(webApplicationContext)
                .apply(SecurityMockMvcConfigurers.springSecurity())
                .build();
    }

    @AfterEach
    void cleanOwnerApiData() {
        for (long horseId : createdHorseIds) {
            jdbcTemplate.update("DELETE FROM dbo.weight_record WHERE horse_id = ?", horseId);
            jdbcTemplate.update("DELETE FROM dbo.veterinary_examination WHERE horse_id = ?", horseId);
            jdbcTemplate.update("DELETE FROM dbo.medical_case WHERE horse_id = ?", horseId);
            jdbcTemplate.update("DELETE FROM dbo.medical_restriction WHERE horse_id = ?", horseId);
            jdbcTemplate.update("DELETE FROM dbo.horse_ownership WHERE horse_id = ?", horseId);
            jdbcTemplate.update("""
                    UPDATE dbo.horse SET sire_horse_id = NULL, dam_horse_id = NULL
                    WHERE sire_horse_id = ? OR dam_horse_id = ?
                    """, horseId, horseId);
        }
        for (long horseId : createdHorseIds) {
            jdbcTemplate.update("DELETE FROM dbo.horse WHERE id = ?", horseId);
        }
        for (long userId : createdUserIds) {
            jdbcTemplate.update("DELETE FROM dbo.user_role WHERE user_id = ?", userId);
            jdbcTemplate.update("DELETE FROM dbo.app_user WHERE id = ?", userId);
        }
    }

    protected long createUser() {
        long userId = NEXT_USER_ID.getAndIncrement();
        jdbcTemplate.update("""
                INSERT INTO dbo.app_user
                    (id, user_code, full_name, email, password_hash, account_status)
                VALUES (?, ?, ?, ?, ?, ?)
                """, userId, "OWN-" + userId, "Owner API Test User",
                "owner-api-" + userId + "@example.test", "test-hash", AccountStatus.ACTIVE.name());
        createdUserIds.add(userId);
        return userId;
    }

    protected long createHorse(
            String name,
            String healthStatus,
            Long sireHorseId,
            String sireName,
            Long damHorseId,
            String damName) {
        String suffix = UUID.randomUUID().toString().replace("-", "").substring(0, 18);
        KeyHolder keyHolder = new GeneratedKeyHolder();
        jdbcTemplate.update(connection -> {
            PreparedStatement statement = connection.prepareStatement("""
                    INSERT INTO dbo.horse
                        (horse_code, name, breed, sex, foaled_date, country_of_origin, registration_no,
                         lifecycle, health_status, sire_horse_id, sire_name, dam_horse_id, dam_name, activated_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, new String[] {"id"});
            statement.setString(1, "H-" + suffix);
            statement.setString(2, name);
            statement.setString(3, "Arabian");
            statement.setString(4, "MARE");
            statement.setObject(5, LocalDate.of(2020, 4, 12));
            statement.setString(6, "Testland");
            statement.setString(7, "REG-" + suffix);
            statement.setString(8, "ACTIVE");
            statement.setString(9, healthStatus);
            statement.setObject(10, sireHorseId);
            statement.setString(11, sireName);
            statement.setObject(12, damHorseId);
            statement.setString(13, damName);
            statement.setObject(14, LocalDateTime.ofInstant(
                    Instant.parse("2025-01-02T03:04:05Z"), ZoneOffset.UTC));
            return statement;
        }, keyHolder);
        Number key = keyHolder.getKey();
        if (key == null) {
            throw new IllegalStateException("H2 did not return the inserted horse id.");
        }
        long horseId = key.longValue();
        createdHorseIds.add(horseId);
        return horseId;
    }

    protected void addOwnership(long horseId, long ownerUserId, String sharePercentage, boolean managing) {
        jdbcTemplate.update("""
                INSERT INTO dbo.horse_ownership
                    (horse_id, owner_user_id, share_percentage, effective_from, effective_to, is_managing_owner)
                VALUES (?, ?, ?, ?, NULL, ?)
                """, horseId, ownerUserId, new java.math.BigDecimal(sharePercentage),
                LocalDate.of(2024, 1, 1), managing);
    }

    protected String bearerToken(long userId, RoleCode role) {
        List<Long> roleIds = jdbcTemplate.query(
                "SELECT id FROM dbo.role WHERE role_code = ?",
                (resultSet, rowNumber) -> resultSet.getLong(1),
                role.name());
        long roleId;
        if (roleIds.isEmpty()) {
            roleId = role.ordinal() + 1L;
            Integer occupiedRoleId = jdbcTemplate.queryForObject(
                    "SELECT COUNT(*) FROM dbo.role WHERE id = ?", Integer.class, roleId);
            if (occupiedRoleId != null && occupiedRoleId > 0) {
                throw new IllegalStateException("The test role id is already assigned to a different role.");
            }
            jdbcTemplate.update("INSERT INTO dbo.role (id, role_code) VALUES (?, ?)", roleId, role.name());
        } else {
            roleId = roleIds.get(0);
        }
        jdbcTemplate.update("INSERT INTO dbo.user_role (id, user_id, role_id) VALUES (?, ?, ?)",
                userId + 10_000L, userId, roleId);
        return jwtTokenService.issue(userId, List.of(role)).value();
    }
}
