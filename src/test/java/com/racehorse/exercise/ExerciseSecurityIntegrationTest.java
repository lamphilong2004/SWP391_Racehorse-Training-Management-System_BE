package com.racehorse.exercise;

import com.racehorse.TestJwtProperties;
import com.racehorse.auth.AccountStatus;
import com.racehorse.auth.PendingRegistrationRepository;
import com.racehorse.auth.RoleCode;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.security.test.web.servlet.setup.SecurityMockMvcConfigurers;
import org.springframework.web.context.WebApplicationContext;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import java.util.Map;
import java.util.concurrent.atomic.AtomicLong;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@ActiveProfiles("test")
class ExerciseSecurityIntegrationTest {

    private static final String PASSWORD = "Exercise-Test-123";

    @Autowired
    private WebApplicationContext context;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private PasswordEncoder passwordEncoder;

    @Autowired
    private JsonMapper objectMapper;

    @MockitoBean
    private PendingRegistrationRepository pendingRegistrationRepository;

    private static final AtomicLong NEXT_ID = new AtomicLong(91_000);
    private MockMvc mockMvc;

    @DynamicPropertySource
    static void jwtProperties(DynamicPropertyRegistry registry) {
        TestJwtProperties.register(registry);
    }

    @BeforeEach
    void setUp() {
        mockMvc = MockMvcBuilders.webAppContextSetup(context)
                .apply(SecurityMockMvcConfigurers.springSecurity())
                .build();
        jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS dbo.exercise_definition (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name NVARCHAR(150) NOT NULL, exercise_type NVARCHAR(50), description NVARCHAR(2000), target_metric NVARCHAR(100), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP)");
        for (RoleCode role : RoleCode.values()) {
            jdbcTemplate.update("MERGE INTO dbo.role KEY(id) VALUES (?, ?)", role.ordinal() + 1, role.name());
        }
    }

    @Test
    void trainerCanCreateListReadAndUpdateExercisesWhileVetCannotWrite() throws Exception {
        long trainerId = createUser(RoleCode.TRAINER);
        String trainerToken = login(trainerId);

        String created = mockMvc.perform(post("/api/exercises")
                        .header("Authorization", "Bearer " + trainerToken)
                        .contentType("application/json")
                        .content("""
                                {"name":"Working walk","exerciseType":"Walk","description":"Low intensity","targetMetric":"duration"}
                                """))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.data.name").value("Working walk"))
                .andReturn().getResponse().getContentAsString();
        JsonNode createdJson = objectMapper.readTree(created);
        long exerciseId = createdJson.path("data").path("id").longValue();

        mockMvc.perform(get("/api/exercises").param("q", "walk").param("exerciseType", "Walk")
                        .header("Authorization", "Bearer " + trainerToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data[0].id").value(exerciseId));
        mockMvc.perform(get("/api/exercises/{id}", exerciseId)
                        .header("Authorization", "Bearer " + trainerToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.targetMetric").value("duration"));
        mockMvc.perform(put("/api/exercises/{id}", exerciseId)
                        .header("Authorization", "Bearer " + trainerToken)
                        .contentType("application/json")
                        .content("""
                                {"name":"Extended walk","exerciseType":"Walk","description":null,"targetMetric":null}
                                """))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.name").value("Extended walk"));

        long veterinarianId = createUser(RoleCode.VETERINARIAN);
        mockMvc.perform(post("/api/exercises")
                        .header("Authorization", "Bearer " + login(veterinarianId))
                        .contentType("application/json")
                        .content("{\"name\":\"Vet forbidden write\"}"))
                .andExpect(status().isForbidden());
        mockMvc.perform(get("/api/exercises/{id}", exerciseId)
                        .header("Authorization", "Bearer " + login(veterinarianId)))
                .andExpect(status().isOk());
    }

    @Test
    void exerciseInputValidationAndMissingIdsUseContractErrors() throws Exception {
        String token = login(createUser(RoleCode.HEAD_TRAINER));
        mockMvc.perform(post("/api/exercises")
                        .header("Authorization", "Bearer " + token)
                        .contentType("application/json")
                        .content("{\"name\":\"   \"}"))
                .andExpect(status().isBadRequest());
        mockMvc.perform(get("/api/exercises/999999")
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isNotFound());
    }

    private long createUser(RoleCode role) {
        long userId = NEXT_ID.getAndIncrement();
        jdbcTemplate.update("INSERT INTO dbo.app_user (id, user_code, full_name, email, password_hash, account_status) VALUES (?, ?, ?, ?, ?, ?)",
                userId, "EX-" + userId, "Exercise User", "exercise-" + userId + "@example.test",
                passwordEncoder.encode(PASSWORD), AccountStatus.ACTIVE.name());
        jdbcTemplate.update("INSERT INTO dbo.user_role (id, user_id, role_id) VALUES (?, ?, ?)",
                userId, userId, role.ordinal() + 1);
        return userId;
    }

    private String login(long userId) throws Exception {
        String email = "exercise-" + userId + "@example.test";
        String body = objectMapper.writeValueAsString(Map.of("email", email, "password", PASSWORD));
        String response = mockMvc.perform(post("/api/auth/login")
                        .contentType("application/json")
                        .content(body))
                .andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString();
        JsonNode login = objectMapper.readTree(response);
        return login.path("data").path("accessToken").stringValue();
    }
}
