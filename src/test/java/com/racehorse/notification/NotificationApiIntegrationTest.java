    @BeforeEach void setup() {
        mvc = MockMvcBuilders.webAppContextSetup(context).apply(springSecurity()).build();
        // Private test-only DDL; production DB-01 and shared test schema remain unchanged.
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS dbo.notification (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient_user_id BIGINT NOT NULL,
                    category VARCHAR(20) NOT NULL, notification_type VARCHAR(50) NOT NULL,
                    title NVARCHAR(200) NOT NULL, message NVARCHAR(1000) NOT NULL,
                    read_at TIMESTAMP NULL, target_type VARCHAR(50) NULL, target_id BIGINT NULL,
                    is_simulated BIT NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL,
                    updated_at TIMESTAMP NULL)
                """);
        jdbc.update("DELETE FROM dbo.notification");
        jdbc.update("DELETE FROM dbo.user_role");
        jdbc.update("DELETE FROM dbo.app_user");
        jdbc.update("DELETE FROM dbo.role");
        for (RoleCode role : RoleCode.values()) {
            jdbc.update("INSERT INTO dbo.role(id,role_code) VALUES (?,?)", role.ordinal() + 1, role.name());
        }
        reset(broker);
    }

    String user(long id, RoleCode role) {
        jdbc.update("INSERT INTO dbo.app_user(id,user_code,full_name,email,password_hash,account_status) VALUES(?,?,?,?,?,'ACTIVE')",
                id, "N" + id, "Notification user " + id, "notification" + id + "@example.test", "unused-fixture-hash");
        jdbc.update("INSERT INTO dbo.user_role(id,user_id,role_id) VALUES (?,?,?)", id, id, role.ordinal() + 1);
        return tokens.issue(id, List.of(role)).value();
    }

    void notification(long id, long recipient, String category, boolean read, boolean simulated) {
        jdbc.update("INSERT INTO dbo.notification(id,recipient_user_id,category,notification_type,title,message,read_at,"
                        + "target_type,target_id,is_simulated,created_at) VALUES(?,?,?,'SESSION_ASSIGNED','Assigned','Assigned session',?,'TRAINING_SESSION',42,?,?)",
                id, recipient, category, read ? LocalDateTime.parse("2026-10-20T12:00:00") : null,
                simulated, LocalDateTime.parse("2026-10-20T10:00:00"));
    }

    @Test void listFiltersPaginatesAndNeverIncludesAnotherRecipient() throws Exception {
        String token = user(1, RoleCode.TRAINER);
        user(2, RoleCode.TRAINER);
        notification(11, 1, "SCHEDULE", false, false);
        notification(12, 1, "MEDICAL", true, false);
        notification(13, 1, "ALERTS", false, true);
        notification(99, 2, "MEDICAL", false, false);
        mvc.perform(get("/api/notifications").param("size", "2").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.items[*].id").value(contains(13, 12)))
                .andExpect(jsonPath("$.data.items[0].isSimulated").value(true))
                .andExpect(jsonPath("$.data.items[0].createdAt").value("2026-10-20T10:00:00Z"))
                .andExpect(jsonPath("$.data.items[0].targetId").value(42))
                .andExpect(jsonPath("$.data.totalItems").value(3)).andExpect(jsonPath("$.data.totalPages").value(2))
                .andExpect(content().string(not(containsString("recipientUserId"))))
                .andExpect(content().string(not(containsString("password"))));
        mvc.perform(get("/api/notifications").param("page", "1").param("size", "2").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.items[*].id").value(contains(11)));
        mvc.perform(get("/api/notifications").param("category", "MEDICAL").param("read", "true")
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.items[*].id").value(contains(12)))
                .andExpect(jsonPath("$.data.items[0].readAt").value("2026-10-20T12:00:00Z"));
        mvc.perform(get("/api/notifications").param("read", "false").param("recipient_user_id", "2")
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.items[*].id").value(contains(13, 11)));
        mvc.perform(get("/api/notifications/unread-count").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.unread").value(2));
    }

    @Test void readIsIdempotentAndForeignOrMissingIdsAreIndistinguishable() throws Exception {
        String token = user(1, RoleCode.GROOM);
        user(2, RoleCode.GROOM);
        notification(11, 1, "SCHEDULE", false, false);
        notification(99, 2, "MEDICAL", false, false);
        Instant beforeRead = Instant.now().minusSeconds(1);
        mvc.perform(patch("/api/notifications/11/read").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.readAt", endsWith("Z")));
        LocalDateTime readAt = jdbc.queryForObject("SELECT read_at FROM dbo.notification WHERE id=11", LocalDateTime.class);
        assertFalse(readAt.toInstant(ZoneOffset.UTC).isBefore(beforeRead));
        assertFalse(readAt.toInstant(ZoneOffset.UTC).isAfter(Instant.now().plusSeconds(1)));
        mvc.perform(patch("/api/notifications/11/read").header("Authorization", "Bearer " + token)).andExpect(status().isOk());
        assertEquals(readAt, jdbc.queryForObject("SELECT read_at FROM dbo.notification WHERE id=11", LocalDateTime.class));
        String foreign = mvc.perform(patch("/api/notifications/99/read").header("Authorization", "Bearer " + token))
                .andExpect(status().isNotFound()).andReturn().getResponse().getContentAsString();
        String missing = mvc.perform(patch("/api/notifications/100/read").header("Authorization", "Bearer " + token))
                .andExpect(status().isNotFound()).andReturn().getResponse().getContentAsString();
        assertEquals(foreign, missing);
        assertNull(jdbc.queryForObject("SELECT read_at FROM dbo.notification WHERE id=99", LocalDateTime.class));
    }

    @Test void readAllMutatesOnlyOwnUnreadRows() throws Exception {
        String token = user(1, RoleCode.HORSE_OWNER);
        user(2, RoleCode.HORSE_OWNER);
        notification(11, 1, "SCHEDULE", false, false);
        notification(12, 1, "MEDICAL", true, false);
        notification(99, 2, "MEDICAL", false, false);
        LocalDateTime originalRead = jdbc.queryForObject("SELECT read_at FROM dbo.notification WHERE id=12", LocalDateTime.class);
        for (int attempt = 0; attempt < 2; attempt++) {
            mvc.perform(post("/api/notifications/read-all").header("Authorization", "Bearer " + token))
                    .andExpect(status().isOk()).andExpect(jsonPath("$.data.unread").value(0));
        }
        assertEquals(originalRead, jdbc.queryForObject("SELECT read_at FROM dbo.notification WHERE id=12", LocalDateTime.class));
        assertNull(jdbc.queryForObject("SELECT read_at FROM dbo.notification WHERE id=99", LocalDateTime.class));
    }

    @ParameterizedTest @EnumSource(RoleCode.class)
    void everyApprovedRoleCanUseItsOwnNotificationEndpoints(RoleCode role) throws Exception {
        String token = user(1, role);
        notification(11, 1, "SCHEDULE", false, false);
        mvc.perform(get("/api/notifications").header("Authorization", "Bearer " + token)).andExpect(status().isOk());
        mvc.perform(get("/api/notifications/unread-count").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.unread").value(1));
        mvc.perform(patch("/api/notifications/11/read").header("Authorization", "Bearer " + token)).andExpect(status().isOk());
        mvc.perform(post("/api/notifications/read-all").header("Authorization", "Bearer " + token)).andExpect(status().isOk());
    }

    @Test void authenticationAccountStatusAndCurrentRolesAreEnforced() throws Exception {
        mvc.perform(get("/api/notifications")).andExpect(status().isUnauthorized());
        mvc.perform(get("/api/notifications/unread-count")).andExpect(status().isUnauthorized());
        mvc.perform(patch("/api/notifications/1/read")).andExpect(status().isUnauthorized());
        mvc.perform(post("/api/notifications/read-all")).andExpect(status().isUnauthorized());
        String token = user(1, RoleCode.TRAINER);
        jdbc.update("UPDATE dbo.app_user SET account_status='INACTIVE' WHERE id=1");
        mvc.perform(get("/api/notifications").header("Authorization", "Bearer " + token)).andExpect(status().isForbidden());
        jdbc.update("UPDATE dbo.app_user SET account_status='ACTIVE' WHERE id=1");
        jdbc.update("DELETE FROM dbo.user_role WHERE user_id=1");
        mvc.perform(get("/api/notifications").header("Authorization", "Bearer " + token)).andExpect(status().isForbidden());
    }

    @Test void invalidFiltersAndPaginationReturnValidationErrors() throws Exception {
        String token = user(1, RoleCode.TRAINER);
        for (String[] query : new String[][]{{"page", "-1"}, {"size", "0"}, {"size", "101"},
                {"category", "EMAIL"}, {"read", "invalid"}}) {
            mvc.perform(get("/api/notifications").param(query[0], query[1]).header("Authorization", "Bearer " + token))
                    .andExpect(status().isBadRequest()).andExpect(jsonPath("$.error.code").value("VALIDATION_ERROR"));
        }
        for (long invalidId : new long[]{0, -1}) {
            mvc.perform(patch("/api/notifications/{id}/read", invalidId).header("Authorization", "Bearer " + token))
                    .andExpect(status().isBadRequest());
        }
        mvc.perform(patch("/api/notifications/not-an-id/read").header("Authorization", "Bearer " + token))
                .andExpect(status().isBadRequest());
    }

    @Test void publisherSendsOnlyAfterCommitAndSuppressesRolledBackWrites() {
        user(1, RoleCode.TRAINER);
        var tx = new TransactionTemplate(transactions);
        tx.executeWithoutResult(status -> {
            notification(11, 1, "ALERTS", false, true);
            publisher.publishAfterCommit(11);
            verify(broker, never()).convertAndSendToUser(anyString(), anyString(), org.mockito.ArgumentMatchers.any(Object.class));
        });
        verify(broker).convertAndSendToUser(eq("1"), eq("/queue/notifications"),
                argThat((Object payload) -> payload instanceof NotificationApi.Notification n
                        && n.id() == 11 && n.isSimulated() && n.targetId() == 42));
        clearInvocations(broker);
        tx.executeWithoutResult(status -> {
            notification(12, 1, "SCHEDULE", false, false);
            publisher.publishAfterCommit(12);
            status.setRollbackOnly();
        });
        verify(broker, never()).convertAndSendToUser(anyString(), anyString(), org.mockito.ArgumentMatchers.any(Object.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.notification WHERE id=12", Integer.class));
    }

    @Test void sessionAssignmentProducerPersistsAndPushesOnlyItsCommittedNotification() {
        user(1, RoleCode.WORK_RIDER);
        var rejected = assertThrows(org.springframework.dao.InvalidDataAccessApiUsageException.class,
                () -> sessionRepository.notifyRider(1, 42, "S-42"));
        assertInstanceOf(IllegalStateException.class, rejected.getRootCause());
        assertEquals("Notification publishing requires the producer's active transaction.", rejected.getRootCause().getMessage());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.notification", Integer.class));
        verify(broker, never()).convertAndSendToUser(anyString(), anyString(), org.mockito.ArgumentMatchers.any(Object.class));
        var tx = new TransactionTemplate(transactions);
        tx.executeWithoutResult(status -> {
            sessionRepository.notifyRider(1, 42, "S-42");
            verify(broker, never()).convertAndSendToUser(anyString(), anyString(), org.mockito.ArgumentMatchers.any(Object.class));
        });
        verify(broker).convertAndSendToUser(eq("1"), eq("/queue/notifications"),
                argThat((Object payload) -> payload instanceof NotificationApi.Notification n
                        && n.id() > 0 && n.notificationType().equals("SESSION_ASSIGNED")
                        && n.category() == NotificationApi.Category.SCHEDULE && !n.isSimulated()
                        && n.targetType().equals("TRAINING_SESSION") && n.targetId() == 42));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.notification WHERE recipient_user_id=1 AND target_id=42", Integer.class));
        clearInvocations(broker);
        tx.executeWithoutResult(status -> {
            sessionRepository.notifyRider(1, 43, "S-43");
            status.setRollbackOnly();
        });
        verify(broker, never()).convertAndSendToUser(anyString(), anyString(), org.mockito.ArgumentMatchers.any(Object.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.notification WHERE target_id=43", Integer.class));
    }
    @Test void publisherRequiresAPersistedRowAndTransactionAndBrokerFailureDoesNotUndoPersistence() {
        user(1, RoleCode.TRAINER);
        notification(11, 1, "SCHEDULE", false, false);
        assertThrows(IllegalStateException.class, () -> publisher.publishAfterCommit(11));
        var tx = new TransactionTemplate(transactions);
        assertThrows(IllegalStateException.class, () -> tx.executeWithoutResult(status -> publisher.publishAfterCommit(404)));
        doThrow(new IllegalStateException("test broker unavailable")).when(broker)
                .convertAndSendToUser(anyString(), anyString(), org.mockito.ArgumentMatchers.any(Object.class));
        assertDoesNotThrow(() -> tx.executeWithoutResult(status -> {
            notification(12, 1, "SCHEDULE", false, false);
            publisher.publishAfterCommit(12);
        }));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM dbo.notification WHERE id=12", Integer.class));
    }
