    @AfterEach
    void clearAuthentication() { SecurityContextHolder.clearContext(); }

    @Test
    void vetAssignmentIsIdempotentAndGroomCompletionSurvivesPlanUpdates() {
        authenticate(10, RoleCode.VETERINARIAN);
        long caseId = medical.create(new CaseCreate(100L, "Bandage wound")).id();
        LocalDate today = LocalDate.now();
        GroomInstruction first = new GroomInstruction("Replace bandage", today, "AM", 20L);
        GroomInstruction second = new GroomInstruction("Check swelling", today.plusDays(1), "AM", 20L);

        long planId = medical.putPlan(caseId, new PlanPut("Medication A", "Rest", "Bandage care", List.of(first), today.plusDays(2))).id();
        assertEquals(1, taskCount(planId));
        medical.putPlan(caseId, new PlanPut("Medication A", "Rest", "Bandage care", List.of(first), today.plusDays(2)));
        assertEquals(1, taskCount(planId));

        long firstTaskId = jdbc.queryForObject("SELECT id FROM dbo.care_task WHERE treatment_plan_id=?", Long.class, planId);
        authenticate(20, RoleCode.GROOM);
        assertEquals(1, groomTasks.list(0, 20).totalElements());
        assertEquals("COMPLETED", groomTasks.complete(firstTaskId, java.util.Map.of()).status());

        authenticate(10, RoleCode.VETERINARIAN);
        medical.putPlan(caseId, new PlanPut("Medication B", "Rest", "Updated care", List.of(first, second), today.plusDays(3)));
        assertEquals(2, taskCount(planId));
        assertEquals("COMPLETED", jdbc.queryForObject("SELECT CASE WHEN completed_at IS NOT NULL AND completed_by_user_id=20 THEN 'COMPLETED' ELSE 'PENDING' END FROM dbo.care_task WHERE id=?", String.class, firstTaskId));

        BusinessException removal = assertThrows(BusinessException.class,
                () -> medical.putPlan(caseId, new PlanPut("Must roll back", null, null, List.of(second), null)));
        assertEquals(ErrorCode.CONFLICT, removal.code());
        assertEquals("Medication B", medical.plan(caseId).treatmentMedicationInstructions());
        assertEquals(2, taskCount(planId));
    }

    private int taskCount(long planId) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM dbo.care_task WHERE treatment_plan_id=?", Integer.class, planId);
    }

    private static void authenticate(long id, RoleCode... roles) {
        List<RoleCode> roleList = List.of(roles);
        CurrentUser user = new CurrentUser(id, "TEST-" + id, "Test Actor", "actor@example.test", roleList, AccountStatus.ACTIVE);
        List<SimpleGrantedAuthority> authorities = roleList.stream()
                .map(role -> new SimpleGrantedAuthority("ROLE_" + role.name())).toList();
        SecurityContextHolder.getContext().setAuthentication(
                UsernamePasswordAuthenticationToken.authenticated(user, null, authorities));
    }
