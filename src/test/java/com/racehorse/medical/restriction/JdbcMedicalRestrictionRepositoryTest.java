package com.racehorse.medical.restriction;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class JdbcMedicalRestrictionRepositoryTest {

    private JdbcTemplate jdbcTemplate;
    private JdbcMedicalRestrictionRepository repository;
    private TransactionTemplate transactionTemplate;

    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:restriction_" + UUID.randomUUID().toString().replace("-", "")
                + ";MODE=MSSQLServer;DB_CLOSE_DELAY=-1");
        jdbcTemplate = new JdbcTemplate(dataSource);
        transactionTemplate = new TransactionTemplate(new DataSourceTransactionManager(dataSource));
        jdbcTemplate.execute("CREATE SCHEMA dbo");
        jdbcTemplate.execute("CREATE TABLE dbo.horse (id BIGINT PRIMARY KEY)");
        jdbcTemplate.execute("CREATE TABLE dbo.medical_case (id BIGINT PRIMARY KEY, horse_id BIGINT NOT NULL)");
        jdbcTemplate.execute("CREATE TABLE dbo.exercise_definition (id BIGINT PRIMARY KEY, name NVARCHAR(150) NOT NULL, exercise_type NVARCHAR(50))");
        jdbcTemplate.execute("""
                CREATE TABLE dbo.medical_restriction (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    horse_id BIGINT NOT NULL,
                    medical_case_id BIGINT,
                    set_by_user_id BIGINT NOT NULL,
                    restriction_level VARCHAR(20) NOT NULL,
                    reason NVARCHAR(1000) NOT NULL,
                    effective_from TIMESTAMP(3) NOT NULL,
                    lifted_at TIMESTAMP(3),
                    review_date DATE,
                    created_at TIMESTAMP(3) NOT NULL,
                    updated_at TIMESTAMP(3),
                    active_horse_id BIGINT GENERATED ALWAYS AS
                        (CASE WHEN lifted_at IS NULL THEN horse_id ELSE NULL END),
                    CONSTRAINT uq_medical_restriction_active_horse UNIQUE (active_horse_id)
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE dbo.restriction_exercise_rule (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    medical_restriction_id BIGINT NOT NULL,
                    exercise_definition_id BIGINT,
                    rule_type VARCHAR(20) NOT NULL,
                    exercise_type_note NVARCHAR(200),
                    created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP(3),
                    FOREIGN KEY (medical_restriction_id) REFERENCES dbo.medical_restriction(id),
                    FOREIGN KEY (exercise_definition_id) REFERENCES dbo.exercise_definition(id),
                    CONSTRAINT ck_test_rule_target CHECK (exercise_definition_id IS NOT NULL OR exercise_type_note IS NOT NULL)
                )
                """);
        jdbcTemplate.update("INSERT INTO dbo.horse (id) VALUES (1)");
        jdbcTemplate.update("INSERT INTO dbo.exercise_definition (id, name, exercise_type) VALUES (5, 'Working trot', 'TROT')");
        repository = new JdbcMedicalRestrictionRepository(jdbcTemplate);
    }

    @Test
    void persistsReadsReplacesRulesAndRetainsLiftedHistory() {
        long restrictionId = repository.insertRestriction(1, null, 44, RestrictionLevel.LIMITED,
                "Operational rest", Instant.parse("2026-10-15T10:00:00Z"), LocalDate.parse("2026-10-20"));
        repository.replaceRules(restrictionId, List.of(
            new ExerciseRule(5L, ExerciseRuleType.ALLOW, null),
            new ExerciseRule(null, ExerciseRuleType.PROHIBIT, "Canter")));

        RestrictionRecord active = repository.findActiveRestriction(1).orElseThrow();
        assertEquals(RestrictionLevel.LIMITED, active.level());
        assertEquals("Operational rest", active.reason());
        assertEquals(44, active.setByUserId());
        assertEquals(ExerciseRuleType.ALLOW, repository.findRules(restrictionId).get(0).ruleType());
        assertEquals("ALLOWED", jdbcTemplate.queryForObject(
                "SELECT rule_type FROM dbo.restriction_exercise_rule WHERE medical_restriction_id = ? ORDER BY id FETCH FIRST 1 ROW ONLY",
                String.class, restrictionId));
        assertEquals("PROHIBITED", jdbcTemplate.queryForObject(
            "SELECT rule_type FROM dbo.restriction_exercise_rule WHERE medical_restriction_id = ? AND rule_type = 'PROHIBITED' FETCH FIRST 1 ROW ONLY",
            String.class, restrictionId));
        assertEquals("TROT", repository.findExerciseType(5).orElseThrow());

        Instant liftedAt = Instant.parse("2026-10-16T10:00:00Z");
        assertEquals(1, repository.liftRestriction(restrictionId, liftedAt));
        assertTrue(repository.findActiveRestriction(1).isEmpty());
        assertEquals(liftedAt, repository.findRestriction(restrictionId).orElseThrow().liftedAt());
        assertFalse(repository.hasActiveRestriction(1));
    }

    @Test
    void concurrentInsertsAreSerializedByTheActiveRestrictionUniqueConstraint() throws Exception {
        ExecutorService executor = Executors.newFixedThreadPool(2);
        CountDownLatch ready = new CountDownLatch(2);
        CountDownLatch start = new CountDownLatch(1);
        try {
            Future<Boolean> first = executor.submit(() -> concurrentInsert(ready, start, 44));
            Future<Boolean> second = executor.submit(() -> concurrentInsert(ready, start, 45));
            ready.await();
            start.countDown();

            assertNotNull(first.get());
            assertNotNull(second.get());
            assertEquals(1, (first.get() ? 1 : 0) + (second.get() ? 1 : 0));
            assertEquals(1, jdbcTemplate.queryForObject(
                    "SELECT COUNT(*) FROM dbo.medical_restriction WHERE horse_id = 1 AND lifted_at IS NULL", Integer.class));
        } finally {
            executor.shutdownNow();
        }
    }

    @Test
    void replacementAndLiftSerializeOnTheSameActiveRestrictionRow() throws Exception {
        long restrictionId = repository.insertRestriction(1, null, 44, RestrictionLevel.LIMITED,
                "Operational rest", Instant.parse("2026-10-15T10:00:00Z"), null);
        ExecutorService executor = Executors.newFixedThreadPool(2);
        CountDownLatch replacementLocked = new CountDownLatch(1);
        CountDownLatch allowReplacementCommit = new CountDownLatch(1);
        CountDownLatch liftAttempting = new CountDownLatch(1);
        try {
            Future<?> replacement = executor.submit(() -> transactionTemplate.execute(status -> {
                assertTrue(repository.findActiveRestrictionForUpdate(restrictionId).isPresent());
                replacementLocked.countDown();
                await(allowReplacementCommit);
                repository.replaceRules(restrictionId,
                        List.of(new ExerciseRule(5L, ExerciseRuleType.ALLOW, null)));
                return null;
            }));
            replacementLocked.await();

            Future<Integer> lift = executor.submit(() -> {
                Integer result = transactionTemplate.execute(status -> {
                    liftAttempting.countDown();
                    Optional<RestrictionRecord> active = repository.findActiveRestrictionForUpdate(restrictionId);
                    return active.isPresent()
                            ? repository.liftRestriction(restrictionId, Instant.parse("2026-10-16T10:00:00Z"))
                            : 0;
                });
                return result;
            });
            liftAttempting.await();
            assertThrows(TimeoutException.class, () -> lift.get(100, TimeUnit.MILLISECONDS));

            allowReplacementCommit.countDown();
            replacement.get();
            assertEquals(1, lift.get());
            assertEquals(1, repository.findRules(restrictionId).size());
            assertTrue(repository.findActiveRestriction(1).isEmpty());
        } finally {
            allowReplacementCommit.countDown();
            executor.shutdownNow();
        }
    }

    private void await(CountDownLatch latch) {
        try {
            latch.await();
        } catch (InterruptedException exception) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Concurrent database test was interrupted.", exception);
        }
    }

    private boolean concurrentInsert(CountDownLatch ready, CountDownLatch start, long actorId) throws Exception {
        ready.countDown();
        start.await();
        try {
            repository.insertRestriction(1, null, actorId, RestrictionLevel.LOCKED,
                    "Operational rest", Instant.parse("2026-10-16T10:00:00Z"), null);
            return true;
        } catch (DuplicateKeyException exception) {
            return false;
        }
    }
}