@SpringBootTest
@ActiveProfiles("test")
class TrainingProgramApiIntegrationTest {

    private static final String PASSWORD = "Program-Test-123";
    private static final AtomicLong NEXT_ID = new AtomicLong(93_000);

    @Autowired private WebApplicationContext context;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private PasswordEncoder passwordEncoder;
    @Autowired private JsonMapper objectMapper;
    @MockitoBean private PendingRegistrationRepository pendingRegistrationRepository;

    private MockMvc mockMvc;

    @DynamicPropertySource
    static void jwtProperties(DynamicPropertyRegistry registry) {
        TestJwtProperties.register(registry);
        registry.add("spring.datasource.url", () -> "jdbc:h2:mem:racehorse_program_api;MODE=MSSQLServer;DB_CLOSE_DELAY=-1");
    }

    @BeforeEach
    void setUp() {
        mockMvc = MockMvcBuilders.webAppContextSetup(context).apply(SecurityMockMvcConfigurers.springSecurity()).build();
        createProgramTables();
        for (RoleCode role : RoleCode.values()) jdbc.update("MERGE INTO dbo.role KEY(id) VALUES (?, ?)", role.ordinal() + 1, role.name());
    }

    @Test
    void headTrainerCreatesTemplateAndProgramAndTrainerReadsOnlyAssignedProgram() throws Exception {
        long headId = createUser(RoleCode.HEAD_TRAINER);
        String headToken = login(headId);
        String templateJson = mockMvc.perform(post("/api/program-templates")
                        .header("Authorization", "Bearer " + headToken)
                        .contentType("application/json")
                        .content("""
                                {"name":"Base Conditioning","goals":"Build stamina","requiredSkillIds":[],"phases":[{"phaseOrder":1,"name":"Foundation","objective":"Easy work","recommendedDuration":"2 weeks","intensityGuidance":"LOW"}]}
                                """))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.data.template.status").value("ACTIVE"))
                .andExpect(jsonPath("$.data.version.versionNo").value(1))
                .andReturn().getResponse().getContentAsString();
        JsonNode template = objectMapper.readTree(templateJson);
        long templateId = template.path("data").path("template").path("id").longValue();
        long versionId = template.path("data").path("version").path("id").longValue();
        mockMvc.perform(get("/api/program-templates").header("Authorization", "Bearer " + headToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.items[0].id").value(templateId));

        long trainerId = createUser(RoleCode.TRAINER);
        long otherTrainerId = createUser(RoleCode.TRAINER);
        long horseId = createHorse();
        jdbc.update("CREATE TABLE IF NOT EXISTS dbo.medical_restriction (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_id BIGINT NOT NULL, restriction_level VARCHAR(20) NOT NULL, reason NVARCHAR(1000), lifted_at TIMESTAMP)");
        jdbc.update("CREATE TABLE IF NOT EXISTS dbo.program_adjustment_request (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_training_program_id BIGINT NOT NULL, status VARCHAR(20) NOT NULL)");
        jdbc.update("CREATE TABLE IF NOT EXISTS dbo.notification (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient_user_id BIGINT NOT NULL, category VARCHAR(20) NOT NULL, notification_type VARCHAR(50) NOT NULL, title NVARCHAR(200) NOT NULL, message NVARCHAR(1000) NOT NULL, target_type VARCHAR(50) NOT NULL, target_id BIGINT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");

        String programJson = mockMvc.perform(post("/api/training-programs")
                        .header("Authorization", "Bearer " + headToken)
                        .contentType("application/json")
                        .content("""
                                {"horseId":%d,"templateVersionId":%d,"name":"Conditioning Block","periodStart":"2026-11-01","periodEnd":"2026-11-30","phases":[{"phaseOrder":1,"name":"Foundation","startDate":"2026-11-01","endDate":"2026-11-15","intensityMin":"LOW","intensityMax":"MEDIUM"}],"trainer":{"trainerUserId":%d,"effectiveFrom":"2026-11-01"}}
                                """.formatted(horseId, versionId, trainerId)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.data.status").value("ACTIVE"))
                .andExpect(jsonPath("$.data.sourceTemplateId").value(templateId))
                .andExpect(jsonPath("$.data.currentTrainer.id").value(trainerId))
                .andReturn().getResponse().getContentAsString();
        long programId = objectMapper.readTree(programJson).path("data").path("id").longValue();

        mockMvc.perform(get("/api/training-programs").header("Authorization", "Bearer " + headToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.items[0].id").value(programId));
        mockMvc.perform(get("/api/training-programs/{id}/progress", programId).header("Authorization", "Bearer " + headToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.phases[0].scheduled").value(0));
        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch("/api/training-programs/{id}/status", programId)
                        .header("Authorization", "Bearer " + headToken).contentType("application/json").content("{\"status\":\"PAUSED\"}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.status").value("PAUSED"));
        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch("/api/training-programs/{id}/status", programId)
                        .header("Authorization", "Bearer " + headToken).contentType("application/json").content("{\"status\":\"ACTIVE\"}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.status").value("ACTIVE"));
        long phaseId = objectMapper.readTree(programJson).path("data").path("phases").get(0).path("id").longValue();
        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put("/api/training-programs/{id}/phases", programId)
                        .header("Authorization", "Bearer " + headToken).contentType("application/json")
                        .content("""
                                {"phases":[{"id":%d,"phaseOrder":1,"name":"Revised Foundation","startDate":"2026-11-01","endDate":"2026-11-15","intensityMin":"LOW","intensityMax":"MEDIUM"}]}
                                """.formatted(phaseId)))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.phases[0].name").value("Revised Foundation"));
        mockMvc.perform(get("/api/training-programs/{id}/history", programId).header("Authorization", "Bearer " + headToken))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.length()").value(5));

        mockMvc.perform(get("/api/training-programs/{id}", programId).header("Authorization", "Bearer " + login(trainerId)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.phases[0].name").value("Revised Foundation"));
        mockMvc.perform(get("/api/training-programs/{id}", programId).header("Authorization", "Bearer " + login(otherTrainerId)))
                .andExpect(status().isForbidden());
        mockMvc.perform(get("/api/program-templates/{id}", templateId).header("Authorization", "Bearer " + headToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.version.name").value("Base Conditioning"));

        mockMvc.perform(post("/api/program-templates/{id}/versions", templateId)
                        .header("Authorization", "Bearer " + headToken).contentType("application/json")
                        .content("""
                                {"name":"Base Conditioning v2","goals":"Build stamina","requiredSkillIds":[],"phases":[{"phaseOrder":1,"name":"Foundation v2"}]}
                                """))
                .andExpect(status().isCreated()).andExpect(jsonPath("$.data.version.versionNo").value(2));
        mockMvc.perform(post("/api/program-templates/{id}/duplicate", templateId)
                        .header("Authorization", "Bearer " + headToken).contentType("application/json")
                        .content("{\"name\":\"Duplicated Block\",\"sourceVersionNo\":1}"))
                .andExpect(status().isCreated()).andExpect(jsonPath("$.data.template.duplicatedFromTemplateId").value(templateId));

        mockMvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put("/api/training-programs/{id}/trainer-assignment", programId)
                        .header("Authorization", "Bearer " + headToken).contentType("application/json")
                        .content("{\"trainerUserId\":" + otherTrainerId + ",\"effectiveFrom\":\"2026-11-16\"}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.currentTrainer.id").value(otherTrainerId));
        mockMvc.perform(get("/api/training-programs/{id}", programId).header("Authorization", "Bearer " + login(trainerId)))
                .andExpect(status().isForbidden());
        mockMvc.perform(get("/api/training-programs/{id}", programId).header("Authorization", "Bearer " + login(otherTrainerId)))
                .andExpect(status().isOk());
        mockMvc.perform(get("/api/training-programs/{id}/history", programId).header("Authorization", "Bearer " + headToken))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.length()").value(6));
    }

    @Test
    void nonHeadTrainerCannotCreateTemplateOrProgram() throws Exception {
        String token = login(createUser(RoleCode.TRAINER));
        mockMvc.perform(post("/api/program-templates")
                        .header("Authorization", "Bearer " + token)
                        .contentType("application/json")
                        .content("{\"name\":\"Denied\",\"phases\":[{\"phaseOrder\":1,\"name\":\"Phase\"}]}"))
                .andExpect(status().isForbidden());
        mockMvc.perform(post("/api/training-programs")
                        .header("Authorization", "Bearer " + token)
                        .contentType("application/json")
                        .content("""
                                {"horseId":1,"templateVersionId":1,"name":"Denied","periodStart":"2026-11-01","periodEnd":"2026-11-30","phases":[{"phaseOrder":1,"name":"Phase","startDate":"2026-11-01","endDate":"2026-11-30"}],"trainer":{"trainerUserId":2,"effectiveFrom":"2026-11-01"}}
                                """))
                .andExpect(status().isForbidden());
    }

    private void createProgramTables() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.training_program_template (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_code VARCHAR(20) NOT NULL UNIQUE, status VARCHAR(20) NOT NULL, duplicated_from_template_id BIGINT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.template_version (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, training_program_template_id BIGINT NOT NULL, created_by_user_id BIGINT, version_no INT NOT NULL, name NVARCHAR(150) NOT NULL, goals NVARCHAR(2000), suitable_horse_profile NVARCHAR(1000), recommended_distance_use_case NVARCHAR(500), recommended_duration NVARCHAR(100), workload_intensity_guidance NVARCHAR(1000), preferred_surfaces NVARCHAR(500), recovery_guidance NVARCHAR(1000), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.template_version_phase (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_version_id BIGINT NOT NULL, phase_order SMALLINT NOT NULL, name NVARCHAR(150) NOT NULL, objective NVARCHAR(1000), recommended_duration NVARCHAR(100), intensity_guidance NVARCHAR(500), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.template_required_skill (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_version_id BIGINT NOT NULL, skill_id BIGINT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.skill (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name NVARCHAR(100) NOT NULL, kind VARCHAR(30) NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.horse (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_code VARCHAR(20) NOT NULL, name NVARCHAR(150) NOT NULL, lifecycle VARCHAR(20) NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.horse_training_program (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_id BIGINT NOT NULL, template_version_id BIGINT NOT NULL, target_race_id BIGINT, created_by_user_id BIGINT NOT NULL, name NVARCHAR(150) NOT NULL, goals NVARCHAR(2000), target_metrics NVARCHAR(1000), period_start DATE NOT NULL, period_end DATE NOT NULL, status VARCHAR(20) NOT NULL, notes NVARCHAR(2000), activated_at TIMESTAMP NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.horse_program_phase (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_training_program_id BIGINT NOT NULL, template_version_phase_id BIGINT, phase_order SMALLINT NOT NULL, name NVARCHAR(150) NOT NULL, objective NVARCHAR(1000), start_date DATE NOT NULL, end_date DATE NOT NULL, intensity_min NVARCHAR(30), intensity_max NVARCHAR(30), workload NVARCHAR(500), is_customized BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.trainer_assignment (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_training_program_id BIGINT NOT NULL, trainer_user_id BIGINT NOT NULL, assigned_by_user_id BIGINT NOT NULL, effective_from DATE NOT NULL, effective_to DATE, reason NVARCHAR(500), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.training_session (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, horse_program_phase_id BIGINT NOT NULL, status VARCHAR(20) NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS dbo.session_result (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, training_session_id BIGINT NOT NULL, evaluation_label NVARCHAR(50), evaluated_at TIMESTAMP NOT NULL)");
    }

    private long createHorse() {
        long id = NEXT_ID.getAndIncrement();
        jdbc.update("INSERT INTO dbo.horse (id,horse_code,name,lifecycle) VALUES (?,?,?,'ACTIVE')", id, "PRG-" + id, "Program Test Horse");
        return id;
    }

    private long createUser(RoleCode role) {
        long id = NEXT_ID.getAndIncrement();
        jdbc.update("INSERT INTO dbo.app_user (id,user_code,full_name,email,password_hash,account_status) VALUES (?,?,?,?,?,?)",
                id, "PG-" + id, "Program User", "program-" + id + "@example.test", passwordEncoder.encode(PASSWORD), AccountStatus.ACTIVE.name());
        jdbc.update("INSERT INTO dbo.user_role (id,user_id,role_id) VALUES (?,?,?)", id, id, role.ordinal() + 1);
        return id;
    }

    private String login(long userId) throws Exception {
        String email = "program-" + userId + "@example.test";
        String response = mockMvc.perform(post("/api/auth/login").contentType("application/json")
                        .content(objectMapper.writeValueAsString(Map.of("email", email, "password", PASSWORD))))
                .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
        JsonNode json = objectMapper.readTree(response);
        return json.path("data").path("accessToken").stringValue();
    }
}
