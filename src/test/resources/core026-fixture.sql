-- Minimal H2 fixture for application persistence tests, NOT proof of DB-01/SQL Server compatibility.
DROP ALL OBJECTS;
CREATE SCHEMA IF NOT EXISTS dbo;
CREATE TABLE dbo.app_user (id BIGINT PRIMARY KEY, user_code VARCHAR(20), full_name VARCHAR(150));
CREATE TABLE dbo.horse (id BIGINT PRIMARY KEY);
CREATE TABLE dbo.horse_training_program (id BIGINT PRIMARY KEY, horse_id BIGINT REFERENCES dbo.horse(id));
CREATE TABLE dbo.horse_program_phase (id BIGINT PRIMARY KEY, horse_training_program_id BIGINT REFERENCES dbo.horse_training_program(id));
CREATE TABLE dbo.training_session (id BIGINT PRIMARY KEY, horse_program_phase_id BIGINT REFERENCES dbo.horse_program_phase(id), work_rider_user_id BIGINT, status VARCHAR(20));
CREATE TABLE dbo.trainer_assignment (id BIGINT PRIMARY KEY, horse_training_program_id BIGINT, trainer_user_id BIGINT, effective_from DATE, effective_to DATE);
CREATE TABLE dbo.care_task (id BIGINT PRIMARY KEY, horse_id BIGINT REFERENCES dbo.horse(id));
CREATE TABLE dbo.pre_session_check (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 training_session_id BIGINT NOT NULL UNIQUE REFERENCES dbo.training_session(id),
 performed_by_user_id BIGINT NOT NULL REFERENCES dbo.app_user(id), performed_at TIMESTAMP(3) NOT NULL,
 observations NVARCHAR(4000), overall_result VARCHAR(20) NOT NULL CHECK(overall_result IN ('ALL_NORMAL','ABNORMAL')),
 created_at TIMESTAMP(3) NOT NULL);
CREATE TABLE dbo.incident (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, incident_code VARCHAR(20) NOT NULL UNIQUE,
 horse_id BIGINT NOT NULL REFERENCES dbo.horse(id), reported_by_user_id BIGINT NOT NULL REFERENCES dbo.app_user(id),
 medical_case_id BIGINT, pre_session_check_id BIGINT REFERENCES dbo.pre_session_check(id),
 training_session_id BIGINT REFERENCES dbo.training_session(id), care_task_id BIGINT REFERENCES dbo.care_task(id),
 observed_at TIMESTAMP(3) NOT NULL, reported_at TIMESTAMP(3) NOT NULL,
 incident_type VARCHAR(30) NOT NULL CHECK(incident_type IN ('OFF_FEED','COLIC_SIGNS','FEVER','HOOF_OR_LEG_PROBLEM','OTHER')),
 observed_severity VARCHAR(20) NOT NULL CHECK(observed_severity IN ('LOW','MEDIUM','HIGH')),
 description NVARCHAR(2000), status VARCHAR(20) NOT NULL CHECK(status IN ('REPORTED','UNDER_REVIEW','RESOLVED')),
 created_at TIMESTAMP(3) NOT NULL, UNIQUE NULLS DISTINCT(pre_session_check_id),
 CHECK ((CASE WHEN pre_session_check_id IS NULL THEN 0 ELSE 1 END)+(CASE WHEN training_session_id IS NULL THEN 0 ELSE 1 END)+(CASE WHEN care_task_id IS NULL THEN 0 ELSE 1 END)<=1));
