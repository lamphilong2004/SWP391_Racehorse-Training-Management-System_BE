CREATE SCHEMA IF NOT EXISTS dbo;

CREATE TABLE IF NOT EXISTS dbo.role (
    id BIGINT PRIMARY KEY,
    role_code VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dbo.app_user (
    id BIGINT PRIMARY KEY,
    user_code VARCHAR(20) NOT NULL UNIQUE,
    full_name NVARCHAR(150) NOT NULL,
    email NVARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    account_status VARCHAR(20) NOT NULL,
    last_login_at TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS dbo.user_role (
    id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS dbo.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    occurred_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_role VARCHAR(30),
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(50),
    target_id BIGINT,
    safe_summary CLOB,
    source VARCHAR(30),
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_log_actor_user FOREIGN KEY (actor_user_id) REFERENCES dbo.app_user (id),
    CONSTRAINT ck_audit_log_actor_role CHECK (
        actor_role IS NULL OR actor_role IN (
            'CLUB_MANAGER','HEAD_TRAINER','TRAINER','WORK_RIDER','VETERINARIAN','GROOM','HORSE_OWNER'
        ))
);
