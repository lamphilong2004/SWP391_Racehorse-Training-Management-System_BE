CREATE SCHEMA IF NOT EXISTS dbo;

CREATE TABLE IF NOT EXISTS dbo.role (
    id BIGINT PRIMARY KEY,
    role_code VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dbo.app_user (
    id BIGINT PRIMARY KEY,
    user_code VARCHAR(20) NOT NULL UNIQUE,
    full_name NVARCHAR(150) NOT NULL,
    email NVARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    account_status VARCHAR(20) NOT NULL,
    last_login_at TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS dbo.user_role (
    id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS dbo.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    occurred_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_role VARCHAR(30),
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(50),
    target_id BIGINT,
    safe_summary CLOB,
    source VARCHAR(30),
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_log_actor_user FOREIGN KEY (actor_user_id) REFERENCES dbo.app_user (id),
    CONSTRAINT ck_audit_log_actor_role CHECK (
        actor_role IS NULL OR actor_role IN (
            'CLUB_MANAGER','HEAD_TRAINER','TRAINER','WORK_RIDER','VETERINARIAN','GROOM','HORSE_OWNER'
        ))
);

CREATE TABLE IF NOT EXISTS dbo.horse (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_code VARCHAR(20) NOT NULL,
        name NVARCHAR(150) NOT NULL,
        breed NVARCHAR(100),
        sex NVARCHAR(20),
        foaled_date DATE,
        country_of_origin NVARCHAR(100),
        registration_no VARCHAR(50),
        lifecycle VARCHAR(20) NOT NULL,
        health_status VARCHAR(20),
        sire_horse_id BIGINT,
        sire_name NVARCHAR(150),
        dam_horse_id BIGINT,
        dam_name NVARCHAR(150),
        activated_at TIMESTAMP(3),
        created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP(3),
        CONSTRAINT uq_test_horse_code UNIQUE (horse_code),
        CONSTRAINT ck_test_horse_lifecycle CHECK (lifecycle IN ('DRAFT', 'ACTIVE', 'INACTIVE')),
        CONSTRAINT ck_test_horse_sire_ref_xor_name CHECK (NOT (sire_horse_id IS NOT NULL AND sire_name IS NOT NULL)),
        CONSTRAINT ck_test_horse_dam_ref_xor_name CHECK (NOT (dam_horse_id IS NOT NULL AND dam_name IS NOT NULL)),
        CONSTRAINT ck_test_horse_sire_not_self CHECK (sire_horse_id IS NULL OR sire_horse_id <> id),
        CONSTRAINT ck_test_horse_dam_not_self CHECK (dam_horse_id IS NULL OR dam_horse_id <> id),
        CONSTRAINT ck_test_horse_sire_not_dam CHECK (
            sire_horse_id IS NULL OR dam_horse_id IS NULL OR sire_horse_id <> dam_horse_id)
);

CREATE TABLE IF NOT EXISTS dbo.horse_ownership (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        owner_user_id BIGINT NOT NULL,
        share_percentage DECIMAL(5, 2) NOT NULL,
        effective_from DATE NOT NULL,
        effective_to DATE,
        is_managing_owner BOOLEAN NOT NULL DEFAULT FALSE,
        CONSTRAINT ck_test_ownership_share CHECK (share_percentage > 0 AND share_percentage <= 100),
        CONSTRAINT fk_test_ownership_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
        CONSTRAINT fk_test_ownership_owner FOREIGN KEY (owner_user_id) REFERENCES dbo.app_user (id)
);

CREATE TABLE IF NOT EXISTS dbo.stable_box (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        box_code VARCHAR(20) NOT NULL UNIQUE,
        yard NVARCHAR(100)
);

CREATE TABLE IF NOT EXISTS dbo.horse_stable_assignment (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        stable_box_id BIGINT NOT NULL,
        assigned_by_user_id BIGINT NOT NULL,
        effective_from DATE NOT NULL,
        effective_to DATE,
        reason NVARCHAR(500),
        updated_at TIMESTAMP(3),
        CONSTRAINT fk_test_assignment_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
        CONSTRAINT fk_test_assignment_box FOREIGN KEY (stable_box_id) REFERENCES dbo.stable_box (id),
        CONSTRAINT fk_test_assignment_actor FOREIGN KEY (assigned_by_user_id) REFERENCES dbo.app_user (id),
        CONSTRAINT ck_test_assignment_reason CHECK (reason IS NULL OR reason <> 'ROLLBACK')
);

CREATE TABLE IF NOT EXISTS dbo.medical_restriction (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        set_by_user_id BIGINT NOT NULL,
        restriction_level VARCHAR(20) NOT NULL,
        reason NVARCHAR(1000) NOT NULL,
        effective_from TIMESTAMP(3) NOT NULL,
        lifted_at TIMESTAMP(3),
        review_date DATE,
        CONSTRAINT fk_test_restriction_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
        CONSTRAINT fk_test_restriction_actor FOREIGN KEY (set_by_user_id) REFERENCES dbo.app_user (id)
);

CREATE TABLE IF NOT EXISTS dbo.medical_case (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        opened_by_user_id BIGINT NOT NULL,
        status VARCHAR(20) NOT NULL,
        opened_at TIMESTAMP(3) NOT NULL,
        closed_at TIMESTAMP(3),
        condition_summary NVARCHAR(2000),
        CONSTRAINT fk_test_case_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
        CONSTRAINT fk_test_case_actor FOREIGN KEY (opened_by_user_id) REFERENCES dbo.app_user (id)
);

CREATE TABLE IF NOT EXISTS dbo.veterinary_examination (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        medical_case_id BIGINT,
        performed_by_user_id BIGINT NOT NULL,
        exam_type VARCHAR(20) NOT NULL,
        examined_at TIMESTAMP(3) NOT NULL,
        health_status_set VARCHAR(20),
        findings NVARCHAR(1000),
        diagnosis NVARCHAR(1000),
        recovery_outcome VARCHAR(20),
        CONSTRAINT ck_test_exam_type CHECK (exam_type IN ('BASELINE', 'EXAMINATION', 'RE_EXAMINATION')),
        CONSTRAINT ck_test_baseline_case CHECK (
            (exam_type = 'BASELINE' AND medical_case_id IS NULL)
            OR (exam_type <> 'BASELINE' AND medical_case_id IS NOT NULL)),
        CONSTRAINT fk_test_exam_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
        CONSTRAINT fk_test_exam_actor FOREIGN KEY (performed_by_user_id) REFERENCES dbo.app_user (id)
);

CREATE TABLE IF NOT EXISTS dbo.weight_record (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        recorded_by_user_id BIGINT NOT NULL,
        weight DECIMAL(6, 2) NOT NULL,
        measured_at TIMESTAMP(3) NOT NULL,
        context NVARCHAR(50),
        CONSTRAINT ck_test_weight_positive CHECK (weight > 0),
        CONSTRAINT fk_test_weight_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id),
        CONSTRAINT fk_test_weight_actor FOREIGN KEY (recorded_by_user_id) REFERENCES dbo.app_user (id)
);

CREATE TABLE IF NOT EXISTS dbo.horse_photo (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        file_reference VARCHAR(500) NOT NULL,
        uploaded_at TIMESTAMP(3) NOT NULL,
        CONSTRAINT fk_test_photo_horse FOREIGN KEY (horse_id) REFERENCES dbo.horse (id)
);

CREATE TABLE IF NOT EXISTS dbo.horse_training_program (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        name NVARCHAR(150) NOT NULL,
        status VARCHAR(20) NOT NULL,
        activated_at TIMESTAMP(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS dbo.horse_program_phase (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_training_program_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS dbo.trainer_assignment (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_training_program_id BIGINT NOT NULL,
        trainer_user_id BIGINT NOT NULL,
        effective_to DATE
);

CREATE TABLE IF NOT EXISTS dbo.training_session (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_code VARCHAR(20) NOT NULL,
        horse_program_phase_id BIGINT NOT NULL,
        scheduled_start TIMESTAMP(3) NOT NULL,
        actual_start TIMESTAMP(3),
        status VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS dbo.incident (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        horse_id BIGINT NOT NULL,
        observed_at TIMESTAMP(3) NOT NULL,
        reported_at TIMESTAMP(3) NOT NULL
);
